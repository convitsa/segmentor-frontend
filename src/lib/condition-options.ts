export function getOptionsForCondition(
  type: string,
  key?: string
): OptionItem[] | null {
  if (type === "geo") {
    if (key === "country") return COUNTRIES;
    if (key === "countryCode") return COUNTRY_CODES;
    return null;
  }
  if (type === "device") return DEVICES;
  if (type === "language") return LANGUAGES;
  if (type === "newReturning") return VISITOR_TYPES;
  if (type === "time" && key === "dayOfWeek") return DAYS_OF_WEEK;
  return null;
}
